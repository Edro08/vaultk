private val lengthMarks = listOf(4, 8, 12, 20, 32, 64, 128)
private val lengthPresets = listOf(8, 12, 20, 32, 64)

private fun sliderPosition(length: Int): Float {
    val segment = lengthMarks.indexOfLast { it <= length }.coerceIn(0, lengthMarks.lastIndex - 1)
    return segment + (length - lengthMarks[segment]).toFloat() /
        (lengthMarks[segment + 1] - lengthMarks[segment])
}

private fun sliderLength(position: Float): Int {
    val segment = position.toInt().coerceIn(0, lengthMarks.lastIndex - 1)
    return (lengthMarks[segment] + (position - segment) *
        (lengthMarks[segment + 1] - lengthMarks[segment])).roundToInt()
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PasswordGeneratorScreen(modifier: Modifier = Modifier, onUse: ((String) -> Unit)? = null) {
    val context = LocalContext.current
    val copyCredential = LocalCopyCredential.current
    val isRtl = LocalLayoutDirection.current == LayoutDirection.Rtl
    var lengthText by remember { mutableStateOf(PasswordOptions().length.toString()) }
    var isSliding by remember { mutableStateOf(false) }
    var options by remember { mutableStateOf(PasswordOptions()) }
    var generated by remember { mutableStateOf<String?>(null) }
    val useButtonRequester = remember { BringIntoViewRequester() }
    LaunchedEffect(generated) {
        if (generated != null && onUse != null) useButtonRequester.bringIntoView()
    }
    var visible by remember { mutableStateOf(true) }
    val length = lengthText.toIntOrNull()
    val valid = length != null && length in PasswordGenerator.MIN_LENGTH..PasswordGenerator.MAX_LENGTH &&
        (options.uppercase || options.lowercase || options.digits || options.symbols)

    fun update(newOptions: PasswordOptions) { options = newOptions; generated = null }
    fun copy(password: String) {
        requireNotNull(copyCredential)(context.getString(R.string.generator_clip_label), password)
        Toast.makeText(context, context.getString(R.string.generator_copied), Toast.LENGTH_SHORT).show()
    }

    Column(modifier.fillMaxSize().verticalScroll(rememberScrollState())
        .padding(VaultkSpacing.normal),
        verticalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
        VaultkCard {
            Column(Modifier.padding(VaultkSpacing.normal),
                verticalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
                    VaultkIconTile(Icons.Default.Straighten, null)
                    Column(Modifier.weight(1f)) {
                        Text(if (isSliding) stringResource(R.string.generator_length_value, lengthText)
                            else stringResource(R.string.generator_length),
                            style = MaterialTheme.typography.titleMedium)
                        Text(stringResource(R.string.generator_length_subtitle),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    OutlinedTextField(lengthText, onValueChange = {
                        if (it.length <= 3 && it.all(Char::isDigit)) {
                            lengthText = it
                            generated = null
                        }
                    }, singleLine = true, keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                        isError = length == null || length !in PasswordGenerator.MIN_LENGTH..PasswordGenerator.MAX_LENGTH,
                        modifier = Modifier.width(76.dp).testTag("generator-length"))
                }
                Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.small)) {
                    Text(PasswordGenerator.MIN_LENGTH.toString(), style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                    Slider(value = sliderPosition((length ?: PasswordGenerator.MIN_LENGTH)
                        .coerceIn(PasswordGenerator.MIN_LENGTH, PasswordGenerator.MAX_LENGTH)),
                        onValueChange = {
                            isSliding = true
                            lengthText = sliderLength(it).toString()
                            generated = null
                        },
                        onValueChangeFinished = { isSliding = false },
                        valueRange = 0f..lengthMarks.lastIndex.toFloat(),
                        track = { state ->
                            val activeTick = MaterialTheme.colorScheme.onPrimary
                            val inactiveTick = MaterialTheme.colorScheme.primary
                            Box {
                                SliderDefaults.Track(sliderState = state)
                                Canvas(Modifier.matchParentSize()) {
                                    for (index in 1 until lengthMarks.lastIndex) {
                                        val fraction = index.toFloat() / lengthMarks.lastIndex
                                        val x = size.width * if (isRtl) 1f - fraction else fraction
                                        drawCircle(
                                            color = if (fraction < state.coercedValueAsFraction)
                                                activeTick else inactiveTick,
                                            radius = 2.dp.toPx(), center = Offset(x, center.y))
                                    }
                                }
                            }
                        }, modifier = Modifier.weight(1f).testTag("generator-slider"))
                    Text(PasswordGenerator.MAX_LENGTH.toString(), style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.small)) {
                    lengthPresets.forEach { preset ->
                        FilterChip(selected = length == preset, onClick = {
                            lengthText = preset.toString()
                            generated = null
                        }, label = { Text(preset.toString()) },
                            modifier = Modifier.weight(1f).heightIn(min = 48.dp)
                                .testTag("generator-preset-$preset"))
                    }
                }
                if (length == null || length !in PasswordGenerator.MIN_LENGTH..PasswordGenerator.MAX_LENGTH) {
                    Text(stringResource(R.string.generator_length_error, PasswordGenerator.MIN_LENGTH,
                        PasswordGenerator.MAX_LENGTH), color = MaterialTheme.colorScheme.error)
                }
            }
        }
        VaultkCard {
            Column(Modifier.padding(vertical = VaultkSpacing.small)) {
                Row(Modifier.fillMaxWidth().padding(horizontal = VaultkSpacing.normal,
                    vertical = VaultkSpacing.small), verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
                    VaultkIconTile(Icons.Default.Settings, null)
                    Column(Modifier.weight(1f)) {
                        Text(stringResource(R.string.generator_types), style = MaterialTheme.typography.titleMedium)
                        Text(stringResource(R.string.generator_types_subtitle),
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
                GeneratorOption(stringResource(R.string.generator_uppercase), options.uppercase) {
                    update(options.copy(uppercase = it))
                }
                HorizontalDivider(Modifier.padding(horizontal = VaultkSpacing.normal))
                GeneratorOption(stringResource(R.string.generator_lowercase), options.lowercase) {
                    update(options.copy(lowercase = it))
                }
                HorizontalDivider(Modifier.padding(horizontal = VaultkSpacing.normal))
                GeneratorOption(stringResource(R.string.generator_digits), options.digits) {
                    update(options.copy(digits = it))
                }
                HorizontalDivider(Modifier.padding(horizontal = VaultkSpacing.normal))
                GeneratorOption(stringResource(R.string.generator_symbols), options.symbols) {
                    update(options.copy(symbols = it))
                }
                if (!options.uppercase && !options.lowercase && !options.digits && !options.symbols) {
                    Text(stringResource(R.string.generator_classes_error), color = MaterialTheme.colorScheme.error,
                        modifier = Modifier.padding(horizontal = VaultkSpacing.normal,
                            vertical = VaultkSpacing.small))
                }
            }
        }
        generated?.let { password ->
            VaultkCard {
                Column(Modifier.padding(VaultkSpacing.normal),
                    verticalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
                    Row(verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.medium)) {
                        VaultkIconTile(Icons.Default.Key, null)
                        Text(stringResource(R.string.generator_preview), style = MaterialTheme.typography.titleMedium)
                    }
                    OutlinedTextField(password, onValueChange = {}, readOnly = true,
                        visualTransformation = if (visible) VisualTransformation.None else PasswordVisualTransformation(),
                        textStyle = MaterialTheme.typography.bodyLarge.copy(fontFamily = FontFamily.Monospace),
                        trailingIcon = {
                            Row {
                                IconButton(onClick = { visible = !visible }) {
                                    Icon(if (visible) Icons.Default.VisibilityOff else Icons.Default.Visibility,
                                        stringResource(if (visible) R.string.common_hide_password else R.string.common_show_password))
                                }
                                IconButton(onClick = { copy(password) }) {
                                    Icon(Icons.Default.ContentCopy, stringResource(R.string.generator_copy))
                                }
                            }
                        }, modifier = Modifier.fillMaxWidth())
                    val alphabetSize = (if (options.uppercase) 26 else 0) +
                        (if (options.lowercase) 26 else 0) + (if (options.digits) 10 else 0) +
                        (if (options.symbols) 13 else 0)
                    val bits = password.length * log2(alphabetSize.toDouble())
                    val level = when {
                        bits < 40 -> 1
                        bits < 60 -> 2
                        bits < 80 -> 3
                        bits < 100 -> 4
                        else -> 5
                    }
                    val color = when {
                        level <= 1 -> MaterialTheme.colorScheme.error
                        level <= 3 -> MaterialTheme.colorScheme.primary
                        else -> MaterialTheme.colorScheme.tertiary
                    }
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.tiny)) {
                        repeat(5) { index ->
                            Box(Modifier.weight(1f).height(6.dp).background(
                                if (index < level) color else MaterialTheme.colorScheme.outlineVariant,
                                RoundedCornerShape(3.dp)))
                        }
                    }
                    Text(stringResource(when {
                        level <= 1 -> R.string.generator_weak
                        level <= 3 -> R.string.generator_moderate
                        level == 4 -> R.string.generator_strong
                        else -> R.string.generator_secure
                    }), color = color, style = MaterialTheme.typography.labelMedium)
                }
            }
        }
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(VaultkSpacing.small)) {
            OutlinedButton(enabled = valid, onClick = {
                generated = PasswordGenerator.generate(options.copy(length = length!!))
                visible = true
            }, modifier = Modifier.weight(1f).heightIn(min = 48.dp),
                border = BorderStroke(1.dp, MaterialTheme.colorScheme.primary)) {
                Icon(Icons.Default.Refresh, null, modifier = Modifier.padding(end = VaultkSpacing.small))
                Text(stringResource(if (generated == null) R.string.generator_generate else R.string.generator_regenerate))
            }
            if (generated != null) {
                Button(onClick = { generated?.let(::copy) },
                    modifier = Modifier.weight(1f).heightIn(min = 48.dp)) {
                    Icon(Icons.Default.ContentCopy, null, modifier = Modifier.padding(end = VaultkSpacing.small))
                    Text(stringResource(R.string.generator_copy))
                }
            }
        }
        if (onUse != null) Button(enabled = generated != null,
            onClick = { generated?.let(onUse) },
            modifier = Modifier.fillMaxWidth().heightIn(min = 48.dp)
                .bringIntoViewRequester(useButtonRequester)) {
            Icon(Icons.Default.Key, null, modifier = Modifier.padding(end = VaultkSpacing.small))
            Text(stringResource(R.string.generator_use))
        }
    }
}

@Composable
private fun GeneratorOption(label: String, checked: Boolean, onChange: (Boolean) -> Unit) {
    Row(Modifier.fillMaxWidth().heightIn(min = 48.dp)
        .toggleable(checked, role = Role.Checkbox, onValueChange = onChange)
        .padding(horizontal = VaultkSpacing.normal, vertical = VaultkSpacing.small),
        verticalAlignment = Alignment.CenterVertically) {
        Text(label, modifier = Modifier.weight(1f), style = MaterialTheme.typography.bodyLarge)
        Checkbox(checked = checked, onCheckedChange = null)
    }
}
